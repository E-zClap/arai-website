// Helper function to calculate H-index
function calculateHIndex(publications) {
  const sortedCitations = publications
    .map(p => p.citations)
    .sort((a, b) => b - a);
  
  let hIndex = 0;
  for (let i = 0; i < sortedCitations.length; i++) {
    if (sortedCitations[i] >= i + 1) {
      hIndex = i + 1;
    } else {
      break;
    }
  }
  return hIndex;
}